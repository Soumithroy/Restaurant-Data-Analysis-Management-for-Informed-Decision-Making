"""Restaurant analytics report.

Runs the KPI queries in kpi_queries.sql against the MySQL database, saves each result as CSV,
draws charts, and writes a Markdown report to reports/REPORT.md.

Usage:
    pip install -r analysis/requirements.txt
    python analysis/analyze.py                       # uses the env vars below or their defaults
Env:
    DB_HOST=127.0.0.1 DB_PORT=3306 DB_USER=root DB_PASSWORD=root DB_NAME=restaurant
"""
from __future__ import annotations

import os
import re
from pathlib import Path

import matplotlib

matplotlib.use("Agg")  # headless (CI / servers)
import matplotlib.pyplot as plt
import pandas as pd
from sqlalchemy import create_engine, text

ROOT = Path(__file__).resolve().parent.parent
QUERIES_FILE = ROOT / "analysis" / "kpi_queries.sql"
OUT = ROOT / "reports"


def engine_from_env():
    url = "mysql+pymysql://{user}:{pw}@{host}:{port}/{db}".format(
        user=os.getenv("DB_USER", "root"),
        pw=os.getenv("DB_PASSWORD", "root"),
        host=os.getenv("DB_HOST", "127.0.0.1"),
        port=os.getenv("DB_PORT", "3306"),
        db=os.getenv("DB_NAME", "restaurant"),
    )
    return create_engine(url)


def load_queries(path: Path = QUERIES_FILE) -> dict[str, str]:
    """Split the .sql file on '-- name: <id>' markers."""
    queries, name, buf = {}, None, []
    for line in path.read_text().splitlines():
        if m := re.match(r"--\s*name:\s*(\w+)", line):
            if name:
                queries[name] = "\n".join(buf).strip().rstrip(";")
            name, buf = m.group(1), []
        elif name and not line.lstrip().startswith("--"):
            buf.append(line)
    if name:
        queries[name] = "\n".join(buf).strip().rstrip(";")
    return queries


def bar(df: pd.DataFrame, x: str, y: str, title: str, file: str, horizontal: bool = False, sort: bool = True):
    fig, ax = plt.subplots(figsize=(8, 4.5))
    data = df.sort_values(y, ascending=horizontal) if sort else df
    (ax.barh if horizontal else ax.bar)(data[x].astype(str), data[y].astype(float), color="#3b6ea5")
    ax.set_title(title, fontsize=13, loc="left")
    ax.spines[["top", "right"]].set_visible(False)
    if not horizontal:
        plt.xticks(rotation=30, ha="right")
    fig.tight_layout()
    fig.savefig(OUT / file, dpi=120)
    plt.close(fig)


def run(engine=None) -> dict[str, pd.DataFrame]:
    OUT.mkdir(exist_ok=True)
    engine = engine or engine_from_env()
    results = {}
    with engine.connect() as conn:
        for name, sql in load_queries().items():
            df = pd.read_sql(text(sql), conn)
            df.to_csv(OUT / f"{name}.csv", index=False)
            results[name] = df

    bar(results["monthly_revenue"], "month", "revenue", "Revenue by month (₹)", "monthly_revenue.png", sort=False)
    bar(results["menu_item_popularity"].head(8), "menu_item_desc", "units_sold",
        "Top menu items by units sold", "top_items.png", horizontal=True)
    bar(results["payment_mix"], "payment_type", "revenue", "Revenue by payment type (₹)", "payment_mix.png")

    write_report(results)
    return results


def write_report(r: dict[str, pd.DataFrame]):
    rev = r["monthly_revenue"]
    total = float(rev["revenue"].sum())
    best_month = rev.loc[rev["revenue"].astype(float).idxmax()]
    top_item = r["menu_item_popularity"].iloc[0]
    top_rest = r["restaurant_ratings"].iloc[0]
    dq = r["dq_invoices_without_order"]

    lines = [
        "# Restaurant Analytics Report",
        "",
        "_Generated by `analysis/analyze.py` from the MySQL database._",
        "",
        "## Key findings",
        "",
        f"- **Total revenue:** ₹{total:,.2f} across {int(rev['invoices'].sum())} invoices "
        f"(average order value ₹{total / rev['invoices'].sum():,.2f}).",
        f"- **Best month:** {best_month['month']} with ₹{float(best_month['revenue']):,.2f}.",
        f"- **Most popular item:** {top_item['menu_item_desc']} ({top_item['cuisine_name']}), "
        f"{int(top_item['units_sold'])} units.",
        f"- **Top-rated restaurant:** {top_rest['res_name']} (avg rating {top_rest['avg_restaurant_rating']}).",
        f"- **Data quality:** {len(dq)} of {int(rev['invoices'].sum())} invoices reference orders with no order "
        "lines → add a FOREIGN KEY from Invoice.order_id and validate at insert time.",
        "",
        "![Monthly revenue](monthly_revenue.png)",
        "",
        "![Top items](top_items.png)",
        "",
        "![Payment mix](payment_mix.png)",
        "",
    ]
    titles = {
        "payment_mix": "Payment mix",
        "delivery_person_performance": "Delivery person performance",
        "restaurant_ratings": "Restaurant ratings",
        "discount_impact": "Discount impact",
        "premium_vs_standard_customers": "Premium vs standard customers",
    }
    for key, title in titles.items():
        lines += [f"## {title}", "", r[key].fillna("–").to_markdown(index=False), ""]
    (OUT / "REPORT.md").write_text("\n".join(lines))


if __name__ == "__main__":
    out = run()
    print(f"Wrote {len(out)} result sets, charts and {OUT / 'REPORT.md'}")
